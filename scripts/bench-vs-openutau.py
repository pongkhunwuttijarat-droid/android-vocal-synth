#!/usr/bin/env python3
"""Benchmark Rusted UTAU (Rust `synth-cli`) against OpenUtau (C# `golden-renderer`).

Both sides render the *same* `.ustx` with the *same* voicebank. The OpenUtau
side and the `r1` engine additionally link the *same* `libworldline.so`, so the
`r1` column isolates host/plumbing overhead while `r1-rs` swaps in the
pure-Rust WORLD kernel.

Run this as ONE process. `/tmp` is a per-invocation tmpfs in this sandbox and
OpenUtau keeps its render cache under `XDG_CACHE_HOME` (= `/tmp/...`), so the
cold/warm protocol is only meaningful inside a single invocation.

    python3 scripts/bench-vs-openutau.py            # full matrix
    python3 scripts/bench-vs-openutau.py --quick    # small projects only
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import statistics
import struct
import subprocess
import sys
import threading
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NATIVE = ROOT / "native"
SYNTH_CLI = NATIVE / "target" / "release" / "synth-cli"
WORLDLINE_SO = NATIVE / "build" / "build-linux" / "libworldline.so"
VOICEBANK_ROOT = ROOT / "test" / "golden" / "teto-english"
# The Rust CLI wants the directory holding character.txt; OpenUtau's loader
# searches recursively, so it is handed the root.
VOICEBANK = VOICEBANK_ROOT / "library"
GOLDEN = ROOT / "test" / "golden" / "golden-renderer"
GOLDEN_BIN = GOLDEN / "bin" / "Release" / "net8.0"
DOTNET = Path(os.environ.get("DOTNET_ROOT", Path.home() / "dotnet")) / "dotnet"
R2_MEL = ROOT / "models" / "r2" / "mel.onnx"
R2_VOCODER = ROOT / "models" / "r2" / "pc-nsf-hifigan" / "pc_nsf_hifigan_44.1k_hop512_128bin_2025.02.onnx"
OUT = ROOT / "out" / "bench"
# Retries per cold run: the reference harness has a phrase-build race.
MAX_ATTEMPTS = 6

PROJECTS = {
    "one-note": ROOT / "test" / "golden" / "one-note.ustx",
    "sakura-test": ROOT / "test" / "golden" / "sakura-test.ustx",
    "scale-demo-app": ROOT / "test" / "golden" / "scale-demo-app.ustx",
    "badapple": ROOT / "test" / "golden" / "badapple.ustx",
    # Generated by scripts/make-badapple-trunc.py: the OpenUtau reference
    # harness silently drops ~23% of badapple.ustx (203 notes) because the
    # async phonemizer races ValidateFull, so this fixture truncates the
    # project at the point OpenUtau actually reaches — making the long-project
    # comparison like-for-like instead of extrapolated.
    "badapple-trunc": OUT / "badapple-trunc.ustx",
}

# Everything either engine may cache. The `res-*.bin` files are RenderCache
# entries (native/crates/runtime/src/cache.rs: `res-{key:016x}.bin`); the
# OpenUtau side keeps its per-phrase WORLD analysis under XDG_CACHE_HOME.
CACHE_ROOTS = [
    Path("/tmp/golden-renderer-cache"),
    Path("/tmp/golden-renderer-data"),
    # Rust RenderCache: <voicebank>/../cache/cache/res-*.bin
    VOICEBANK_ROOT / "cache",
    ROOT / "test" / "golden" / "cache",
]


# ---------------------------------------------------------------- measurement


def _status_field(pid: int, field: str) -> float | None:
    try:
        with open(f"/proc/{pid}/status") as fh:
            for line in fh:
                if line.startswith(field):
                    return float(line.split()[1])
    except OSError:
        pass
    return None


def _proc_snapshot() -> dict[int, tuple[int, int]]:
    """pid -> (ppid, rss_kb) for every live process."""
    out = {}
    for entry in os.listdir("/proc"):
        if not entry.isdigit():
            continue
        pid = int(entry)
        try:
            with open(f"/proc/{pid}/stat", "rb") as fh:
                data = fh.read()
            rparen = data.rfind(b")")
            fields = data[rparen + 2:].split()
            ppid = int(fields[1])
            rss_pages = int(fields[21])
        except (OSError, IndexError, ValueError):
            continue
        out[pid] = (ppid, rss_pages * (os.sysconf("SC_PAGE_SIZE") // 1024))
    return out


def _tree_rss(pid: int) -> int:
    snap = _proc_snapshot()
    if pid not in snap:
        return 0
    children: dict[int, list[int]] = {}
    for p, (ppid, _) in snap.items():
        children.setdefault(ppid, []).append(p)
    total, stack, seen = 0, [pid], set()
    while stack:
        p = stack.pop()
        if p in seen:
            continue
        seen.add(p)
        total += snap[p][1]
        stack.extend(children.get(p, ()))
    return total


class Result:
    __slots__ = ("wall", "cpu_user", "cpu_sys", "peak_rss", "tree_rss", "rc", "log")

    def __init__(self, wall, cpu_user, cpu_sys, peak_rss, tree_rss, rc, log):
        self.wall, self.cpu_user, self.cpu_sys = wall, cpu_user, cpu_sys
        self.peak_rss, self.tree_rss, self.rc, self.log = peak_rss, tree_rss, rc, log

    @property
    def cpu(self):
        return self.cpu_user + self.cpu_sys

    @property
    def cores(self):
        return self.cpu / self.wall if self.wall > 0 else 0.0

    def as_dict(self):
        return {
            "wall_s": round(self.wall, 3),
            "cpu_s": round(self.cpu, 3),
            "cores": round(self.cores, 2),
            "peak_rss_mb": round(self.peak_rss / 1024, 1),
            "tree_rss_mb": round(self.tree_rss / 1024, 1),
            "rc": self.rc,
        }


def run_measured(argv: list[str], *, cwd: Path, env: dict[str, str], log: Path) -> Result:
    """fork/exec `argv`, sampling /proc for peak RSS while it runs."""
    peaks: list[int] = []
    trees: list[int] = []
    log.parent.mkdir(parents=True, exist_ok=True)
    with open(log, "wb") as fh:
        pid = os.fork()
        if pid == 0:  # child
            try:
                os.dup2(fh.fileno(), 1)
                os.dup2(fh.fileno(), 2)
                os.chdir(cwd)
                os.environ.update(env)
                os.execvp(argv[0], argv)
            except BaseException:
                os._exit(127)
        stop = threading.Event()

        def sample():
            while not stop.is_set():
                hwm = _status_field(pid, "VmHWM:")
                if hwm is not None:
                    peaks.append(int(hwm))
                    trees.append(_tree_rss(pid))
                stop.wait(0.01)

        t0 = time.perf_counter()
        th = threading.Thread(target=sample, daemon=True)
        th.start()
        _, status, ru = os.wait4(pid, 0)
        wall = time.perf_counter() - t0
        stop.set()
        th.join(timeout=1.0)

    rc = os.waitstatus_to_exitcode(status)
    return Result(
        wall=wall,
        cpu_user=ru.ru_utime,
        cpu_sys=ru.ru_stime,
        peak_rss=max(peaks, default=ru.ru_maxrss),
        tree_rss=max(trees, default=0),
        rc=rc,
        log=str(log),
    )


def wav_seconds(path: Path) -> float:
    try:
        with open(path, "rb") as fh:
            fh.seek(24)
            rate = struct.unpack("<I", fh.read(4))[0]
            fh.seek(40)
            data = struct.unpack("<I", fh.read(4))[0]
        return round(data / (rate * 2), 2) if rate else 0.0
    except OSError:
        return 0.0


# ------------------------------------------------------------------- engines


def clear_caches() -> None:
    for root in CACHE_ROOTS:
        shutil.rmtree(root, ignore_errors=True)


def cache_listing() -> set[str]:
    found = set()
    for root in CACHE_ROOTS:
        if root.is_dir():
            for p in root.rglob("*"):
                if p.is_file():
                    found.add(str(p.relative_to(ROOT)) if str(p).startswith(str(ROOT)) else str(p))
    return found


def rust_argv(engine: str, project: Path, out: Path, *, threads: int | None, verbose: bool) -> list[str]:
    argv = [
        str(SYNTH_CLI), "render",
        "--engine", engine,
        "--project", str(project),
        "--voicebank", str(VOICEBANK),
        "--out", str(out),
        # Required by the CLI even for r1-rs (which ignores it and uses the
        # pure-Rust kernel) — keep it identical across engines.
        "--so", str(WORLDLINE_SO),
    ]
    if engine == "r2":
        argv += ["--mel-onnx", str(R2_MEL), "--vocoder-onnx", str(R2_VOCODER)]
    if verbose:
        argv.append("--verbose")
    return argv


def rust_env(threads: int | None) -> dict[str, str]:
    env = {"RAYON_NUM_THREADS": str(threads)} if threads else {}
    return env


def openutau_argv(project: Path, out: Path) -> list[str]:
    return [str(DOTNET), "OpenUtau.Test.dll", "phrase", str(out), str(project)]


def openutau_env() -> dict[str, str]:
    # No runtime handicaps: the .NET host runs with its stock defaults.
    # TETO_DIR is the bank root; OpenUtau's VoicebankLoader searches it.
    return {"TETO_DIR": str(VOICEBANK_ROOT)}


# ---------------------------------------------------------------------- main


def measure(label: str, argv, cwd, env, out_wav, *, repeats: int, warm: bool):
    """`repeats` cold runs (cache cleared) then one warm run after each.

    The OpenUtau reference harness has a known race in classic mode: the
    async phonemizer can still be settling when `ValidateFull` builds the
    render phrases, yielding "phrases: 0" and rc=2. Those runs are retried
    and never contribute to a median.
    """
    cold, warm_runs, failures = [], [], 0
    for i in range(repeats):
        for attempt in range(MAX_ATTEMPTS):
            clear_caches()
            r = run_measured(argv, cwd=cwd, env=env,
                             log=OUT / "logs" / f"{label}-cold{i}-a{attempt}.log")
            if r.rc == 0:
                break
            failures += 1
            print(f"    ! {label} cold#{i} attempt {attempt}: rc={r.rc} — retrying")
        else:
            print(f"    !! {label} cold#{i}: gave up after {MAX_ATTEMPTS} attempts")
        cold.append(r)
        if warm:
            r2 = run_measured(argv, cwd=cwd, env=env,
                              log=OUT / "logs" / f"{label}-warm{i}.log")
            warm_runs.append(r2)
    audio = wav_seconds(out_wav)
    return {"cold": cold, "warm": warm_runs, "audio_s": audio, "failures": failures}


def summarize(runs, audio_s, failures=0):
    ok = [r for r in runs if r.rc == 0]
    if not ok:
        return None
    med = lambda xs: round(statistics.median(xs), 3)
    return {
        "wall_s": med([r.wall for r in ok]),
        "cpu_s": med([r.cpu for r in ok]),
        "cores": round(med([r.cores for r in ok]), 2),
        "peak_rss_mb": round(med([r.peak_rss for r in ok]) / 1024, 1),
        "realtime_x": round(audio_s / med([r.wall for r in ok]), 2) if audio_s else None,
        "n_ok": len(ok),
        "n_failed": failures + (len(runs) - len(ok)),
        "rc": [r.rc for r in runs],
    }


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true", help="small projects only")
    ap.add_argument("--repeats", type=int, default=3)
    ap.add_argument("--only", default=None, help="comma-separated engines to run")
    ap.add_argument("--projects", default=None, help="comma-separated projects to run")
    ap.add_argument("--section", default="matrix,scaling,pin",
                    help="comma-separated subset of: matrix, scaling, pin")
    args = ap.parse_args()
    args.section = [s.strip() for s in args.section.split(",") if s.strip()]

    for required in (SYNTH_CLI, WORLDLINE_SO, DOTNET, GOLDEN_BIN / "OpenUtau.Test.dll", VOICEBANK):
        if not Path(required).exists():
            print(f"MISSING: {required}", file=sys.stderr)
            return 2
    OUT.mkdir(parents=True, exist_ok=True)
    shutil.rmtree(OUT / "logs", ignore_errors=True)

    print("=== environment ===")
    print(f"  synth-cli : {SYNTH_CLI}")
    print(f"  dotnet    : {subprocess.run([str(DOTNET), '--version'], capture_output=True, text=True).stdout.strip()}")
    print(f"  worldline : {WORLDLINE_SO}")
    print(f"  voicebank : {VOICEBANK}")

    projects = ["one-note", "sakura-test"] if args.quick else list(PROJECTS)
    if args.projects:
        projects = [p.strip() for p in args.projects.split(",") if p.strip()]
    engines = (args.only.split(",") if args.only
               else ["openutau", "r1", "r1-rs"] if args.quick
               else ["openutau", "r1", "r1-rs"])
    # r2 (neural) is a different synthesis path, so it is not a like-for-like
    # OpenUtau comparison — one informational row only.
    informational = [("scale-demo-app", "r2")] if not args.quick and not args.projects else []

    # Cache-location probe: prove the protocol actually starts cold.
    print("\n=== cache probe (r1, sakura-test) ===")
    clear_caches()
    before = cache_listing()
    probe_out = OUT / "probe-r1.wav"
    probe = run_measured(rust_argv("r1", PROJECTS["sakura-test"], probe_out, threads=None, verbose=False),
                         cwd=ROOT, env={}, log=OUT / "logs" / "probe.log")
    after = cache_listing()
    print(f"  run rc={probe.rc} wall={probe.wall:.2f}s")
    print(f"  new cache files: {len(after - before)}")
    for p in sorted(after - before)[:5]:
        print(f"    + {p}")

    results: dict[str, dict] = {}
    results_path = OUT / "results.json"
    if results_path.exists():
        try:
            results = json.loads(results_path.read_text())
        except ValueError:
            results = {}

    def save():
        results_path.write_text(json.dumps(results, indent=2))

    sections = args.section
    projects = ["one-note", "sakura-test"] if args.quick else list(PROJECTS)
    if args.projects:
        projects = [p.strip() for p in args.projects.split(",") if p.strip()]
    engines = (args.only.split(",") if args.only
               else ["openutau", "r1", "r1-rs"] if args.quick
               else ["openutau", "r1", "r1-rs"])
    # r2 (neural) is a different synthesis path, so it is not a like-for-like
    # OpenUtau comparison — one informational row only.
    informational = [("scale-demo-app", "r2")] if not args.quick and not args.projects else []

    if "pin" in sections:
        results["_single_core"] = single_core_experiment(args.repeats)
        save()

    if "matrix" in sections:
        # Cache-location probe: prove the protocol actually starts cold.
        print("\n=== cache probe (r1, sakura-test) ===")
        clear_caches()
        before = cache_listing()
        probe_out = OUT / "probe-r1.wav"
        probe = run_measured(rust_argv("r1", PROJECTS["sakura-test"], probe_out, threads=None, verbose=False),
                             cwd=ROOT, env={}, log=OUT / "logs" / "probe.log")
        after = cache_listing()
        print(f"  run rc={probe.rc} wall={probe.wall:.2f}s")
        print(f"  new cache files: {len(after - before)}")
        for p in sorted(after - before)[:5]:
            print(f"    + {p}")

        worklist = [(p, e) for p in projects for e in engines] + informational
        for pname, engine in worklist:
            project = PROJECTS[pname]
            label = f"{engine}__{pname}"
            out_wav = OUT / f"{label}.wav"
            if engine == "openutau":
                argv, cwd, env = openutau_argv(project, out_wav), GOLDEN_BIN, openutau_env()
            else:
                argv = rust_argv(engine, project, out_wav, threads=None, verbose=False)
                cwd, env = ROOT, rust_env(None)
            data = measure(label, argv, cwd, env, out_wav, repeats=args.repeats, warm=True)
            entry = {
                "engine": engine,
                "project": pname,
                "audio_s": data["audio_s"],
                "cold": summarize(data["cold"], data["audio_s"], data["failures"]),
                "warm": summarize(data["warm"], data["audio_s"]),
            }
            results[label] = entry
            # Persist after every config so a later failure cannot lose the matrix.
            save()
            print(f"\n[{label}] audio={entry['audio_s']}s")
            print(f"  cold: {entry['cold']}")
            if entry["warm"]:
                print(f"  warm: {entry['warm']}")

    if "scaling" in sections:
        results["_scaling"] = thread_scaling(args.repeats)
        save()

    print(f"\nwrote {results_path}")
    return 0


PIN_JOBS = ["scale-demo-app", "badapple-trunc"]


def single_core_experiment(repeats: int) -> dict:
    """Pin each side to one CPU with taskset.

    OpenUtau's RenderEngine renders phrases strictly sequentially, but its
    measured wall/CPU ratio is ~2, so `taskset -c 0` answers the question
    directly: how much of its 30 s on badapple is inherently serial? The Rust
    side is pinned the same way *and* limited to one rayon worker, so both
    numbers are "one core, cold cache, same project, same kernel".
    """
    print("\n\n=== single-core control (taskset -c 0, cold) ===")
    rows: dict[str, dict] = {}
    for pname in PIN_JOBS:
        project = PROJECTS[pname]
        pin = ["taskset", "-c", "0"]
        for who, engine in (("openutau", None), ("r1-1thread", "r1"), ("r1-rs-1thread", "r1-rs")):
            label = f"pin-{who}__{pname}"
            out_wav = OUT / f"{label}.wav"
            if engine is None:
                argv, cwd, env = pin + openutau_argv(project, out_wav), GOLDEN_BIN, openutau_env()
            else:
                argv = pin + rust_argv(engine, project, out_wav, threads=1, verbose=False)
                cwd, env = ROOT, rust_env(1)
            data = measure(label, argv, cwd, env, out_wav, repeats=repeats, warm=False)
            row = summarize(data["cold"], data["audio_s"], data["failures"]) or {
                "error": "all runs failed"}
            row["audio_s"] = data["audio_s"]
            rows[f"{pname}::{who}"] = row
            print(f"  {label}: {row}")
    return rows


SCALING_JOBS = [
    ("scale-demo-app", 1, 2),
    ("scale-demo-app", 2, 2),
    ("scale-demo-app", 4, 2),
    ("scale-demo-app", 12, 2),
    ("badapple", 1, 1),
    ("badapple", 12, 1),
]


def thread_scaling(_repeats: int) -> dict:
    """Rust r1 with a pinned rayon thread count vs the sequential OpenUtau."""
    print("\n\n=== thread scaling (cold, r1) ===")
    rows: dict[str, dict] = {}
    for pname, n, reps in SCALING_JOBS:
        project = PROJECTS[pname]
        label = f"r1-t{n}__{pname}"
        out_wav = OUT / f"{label}.wav"
        data = measure(
            label,
            rust_argv("r1", project, out_wav, threads=n, verbose=False),
            ROOT,
            rust_env(n),
            out_wav,
            repeats=reps,
            warm=False,
        )
        key = f"{pname}@t{n}"
        rows[key] = summarize(data["cold"], data["audio_s"], data["failures"])
        print(f"  {label}: {rows[key]}")
    return rows


if __name__ == "__main__":
    sys.exit(main())
